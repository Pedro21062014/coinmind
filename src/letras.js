export const FONT = F;

/** Remove acentos e mantém só caracteres suportados. */
export function normalizar(texto) {
  return String(texto)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase();
}

/**
 * Renderiza um texto em letras gigantes estilo ANSI Shadow.
 * @param {string} texto texto a renderizar (A-Z, 0-9, . ! - e espaço)
 * @returns {string} arte ASCII em 6 linhas
 */
export function renderizarLetras(texto) {
  const chars = normalizar(texto).slice(0, 40).split('');
  const linhas = ['', '', '', '', '', ''];
  for (const ch of chars) {
    const g = F[ch] || F[' '];
    const largura = Math.max(...g.map((r) => r.length));
    for (let i = 0; i < 6; i++) linhas[i] += g[i].padEnd(largura, ' ') + ' ';
  }
  return linhas.map((l) => l.replace(/\s+$/, '')).join('\n');
}

/** Fonte suportada (para mensagens de erro). */
export function caracteresSuportados() {
  return 'A-Z 0-9 . ! - espaço';
}
